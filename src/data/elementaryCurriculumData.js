// ── NEIS 자동 평어 문장 생성기 (선생님 자유 작성 평가요소 NLP 합성 엔진) ──
export const generateNeisComment = (elementText, achievementLevel) => {
    if (!elementText || !achievementLevel) return '';

    // 문장 정제: 끝의 '수 있는가?', '하는가?', '인가?' 질문형 어미 제거
    let cleanText = elementText.trim()
        .replace(/\?$/g, '')
        .replace(/(할 수 있는가|할 수 있는가|수 있는가|하는가|인가|하는가요)$/g, '')
        .trim();

    // 성취 수준별 (HIGH: ◎ 매우잘함, MID: ◯ 잘함, LOW: △ 보통) 문장 완성
    if (achievementLevel === 'HIGH' || achievementLevel === '◎' || achievementLevel === 3) {
        if (cleanText.endsWith('다')) {
            return `${cleanText.slice(0, -1)}며, 성취기준을 매우 우수하게 달성함.`;
        }
        return `${cleanText} 능력이 매우 뛰어나며, 성취기준을 완벽히 이해하고 주도적으로 수행함.`;
    } else if (achievementLevel === 'MID' || achievementLevel === '◯' || achievementLevel === '○' || achievementLevel === 2) {
        if (cleanText.endsWith('다')) {
            return `${cleanText.slice(0, -1)}며, 성취기준을 충실히 잘 수행함.`;
        }
        return `${cleanText} 능력이 양호하며, 안내에 따라 성취기준을 무난히 달성함.`;
    } else if (achievementLevel === 'LOW' || achievementLevel === '△' || achievementLevel === 1) {
        if (cleanText.endsWith('다')) {
            return `${cleanText.slice(0, -1)}는 데 기초적 이해가 필요하며, 보충 학습을 통해 발전 가능성이 있음.`;
        }
        return `${cleanText} 능력 향상을 위해 지속적인 관심과 추가적인 연습이 필요함.`;
    }

    return `${cleanText} 성취 수준 평가를 완료함.`;
};
